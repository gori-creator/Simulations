export type IconName = keyof typeof PATHS;

export function icon(name: IconName, size = 18): SVGSVGElement {
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('class', `zf-ico zf-ico--${name}`);
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.innerHTML = PATHS[name];
  return svg;
}

/** Knopf-Inhalt setzen: Symbol und Beschriftung (Beschriftung als eigenes span). */
export function setButton(button: HTMLElement, name: IconName | null, label: string): void {
  const span = document.createElement('span');
  span.className = 'zf-btn__label';
  span.textContent = label;
  button.replaceChildren(...(name ? [icon(name)] : []), span);
}
